int uio_font_cell(int ch)
{
    if (ch >= 'a' && ch <= 'z') ch -= 32;                 /* fold to uppercase */
    if (ch < UIO_FONT_FIRST || ch >= UIO_FONT_FIRST + UIO_FONT_COUNT) return -1;
    return ch - UIO_FONT_FIRST;
}

void uio_bake_font_atlas(uint16_t *out)
{
    if (!out) return;
    for (int i = 0; i < UIO_FONT_ATLAS_TEXELS; i++) out[i] = 0;   /* A4=0 = skip-write */

    for (int cell = 0; cell < UIO_FONT_COUNT; cell++) {
        int ox = uio_font_cell_x(cell), oy = uio_font_cell_y(cell);
        for (int row = 0; row < UIO_FONT_INK_H; row++) {
            const char *src = GLYPHS[cell][row];
            for (int col = 0; col < UIO_FONT_INK_W; col++) {
                if (src[col] != '#') continue;
                out[(size_t)(oy + row) * UIO_FONT_ATLAS_W + (size_t)(ox + col)] = 0xFFFFu;
            }
        }
    }
}
